// runGen chạy routegen trên tệp in, ghi ra một tệp tạm; trả mã thoát, stderr và nội dung đã sinh.
func runGen(t *testing.T, in string) (code int, stderr, out string) {
	t.Helper()
	outPath := filepath.Join(t.TempDir(), "routes_gen.go")
	var errBuf bytes.Buffer
	code = run([]string{"-in", in, "-out", outPath}, &errBuf)
	b, err := os.ReadFile(outPath)
	if err != nil && code == 0 {
		t.Fatalf("thoát 0 mà không có tệp sinh: %v", err)
	}
	return code, errBuf.String(), string(b)
}

func TestRejectsBadContracts(t *testing.T) {
	cases := []struct {
		file string
		want []string // mỗi chuỗi phải có trong stderr
	}{
		{"missing-permission.yaml", []string{"forgotPermission", "x-permission"}},
		{"write-without-key.yaml", []string{"deleteThingNoKey", "IdempotencyKey"}},
		{"both-markers.yaml", []string{"bothMarkers"}},
		{"bad-markers.yaml", []string{"publicFalse", "emptyPermission", "GET /api/v1/c", "operationId"}},
		// Task 315: x-authenticated (chỉ cần đăng nhập) loại trừ hai dấu kia, chỉ nhận true, chỉ trên route đọc.
		{"authenticated-bad.yaml", []string{"authWithPermission", "authWithPublic", "authFalse", "authOnWrite", "x-authenticated"}},
		// ADR-47: mỗi dòng của bảng luật ở điểm 2.
		{"exempt-no-reason.yaml", []string{"exemptMissingReason", "exemptBlankReason", "reasonWithoutMode", "x-idempotency-reason"}},
		{"exempt-on-get.yaml", []string{"exemptGet", "exemptPut", "POST"}},
		{"exempt-with-key.yaml", []string{"exemptWithKey", "IdempotencyKey"}},
		{"idempotency-unknown.yaml", []string{"unknownMode", "safe"}},
		{"noreplay-no-key.yaml", []string{"noReplayNoKey", "IdempotencyKey"}},
		{"noreplay-no-reason.yaml", []string{"noReplayNoReason", "noReplayOnDelete", "x-idempotency-reason", "POST"}},
		// M5-05 (luật openapi 6): /api/v1/web/* ⇔ x-auth: service_key; khóa dịch vụ chỉ mang quyền web.*.
		{"web-path-access.yaml", []string{"webNoAuth", "thingsServiceKey", "webAuthAccess", "webPublic", "webStaffPermission", "x-auth"}},
		{"admission-on-access.yaml", []string{"admissionOnAccess", "admissionOnExempt", "admissionOnRead", "admissionBadName", "x-admission"}},
		{"body-limit-too-big.yaml", []string{"bodyTooBig", "bodyTooSmall", "bodyNotInt", "x-body-limit"}},
	}
	for _, c := range cases {
		t.Run(c.file, func(t *testing.T) {
			code, stderr, out := runGen(t, filepath.Join("testdata", c.file))
			if code == 0 {
				t.Fatalf("hợp đồng sai phải thoát khác 0; đã sinh:\n%s", out)
			}
			if out != "" {
				t.Fatalf("hợp đồng sai không được ghi tệp sinh, có:\n%s", out)
			}
			for _, w := range c.want {
				if !strings.Contains(stderr, w) {
					t.Errorf("stderr phải nêu %q, có:\n%s", w, stderr)
				}
			}
		})
	}
	if t.Failed() {
		return
	}
	// Operation đúng trong cùng tệp không bị báo.
	for file, ok := range map[string]string{
		"missing-permission.yaml":  "okRead",
		"web-path-access.yaml":     "webOk",
		"admission-on-access.yaml": "admissionOk",
		"body-limit-too-big.yaml":  "bodyOk",
	} {
		_, stderr, _ := runGen(t, filepath.Join("testdata", file))
		if strings.Contains(stderr, ok) {
			t.Errorf("%s: operation hợp lệ %s không được bị báo:\n%s", file, ok, stderr)
		}
	}
}

func TestGeneratesRoutes(t *testing.T) {
	code, stderr, out := runGen(t, filepath.Join("testdata", "ok.yaml"))
	if code != 0 {
		t.Fatalf("ok.yaml phải sinh được: %d\n%s", code, stderr)
	}
	for _, w := range []string{
		"// Code generated by tools/routegen. DO NOT EDIT.",
		"type Route struct",
		`{Method: "GET", Pattern: "GET /health/live", OperationID: "live", Public: true, Auth: "public"}`,
		`{Method: "GET", Pattern: "GET /api/v1/me", OperationID: "me", Authenticated: true, Auth: "access"}`,
		"Authenticated ",
		// IdempotencyKey khai ở mức đường dẫn cũng được tính.
		`{Method: "PUT", Pattern: "PUT /api/v1/things/{id}", OperationID: "putThing", Permission: "things.write", Write: true, IdempotencyMode: "required", Auth: "access"}`,
		`{Method: "POST", Pattern: "POST /api/v1/things", OperationID: "createThing", Permission: "things.write", Write: true, IdempotencyMode: "required", Auth: "access"}`,
		`{Method: "GET", Pattern: "GET /api/v1/events", OperationID: "events", Permission: "things.read", Stream: true, Auth: "access"}`,
	} {
		if !strings.Contains(out, w) {
			t.Errorf("tệp sinh thiếu %q:\n%s", w, out)
		}
	}
	// Thứ tự cố định theo đường dẫn rồi method: chạy lại ra đúng từng byte.
	_, _, again := runGen(t, filepath.Join("testdata", "ok.yaml"))
	if again != out {
		t.Fatal("hai lần sinh khác nhau")
	}
}

// genOK sinh từ testdata/file; thoát khác 0 thì test dừng.
func genOK(t *testing.T, file string) string {
	t.Helper()
	code, stderr, out := runGen(t, filepath.Join("testdata", file))
	if code != 0 {
		t.Fatalf("%s phải sinh được: %d\n%s", file, code, stderr)
	}
	return out
}

// ADR-47: route exempt, no-replay mang cờ và lý do (đã bỏ khoảng trắng hai đầu); route ghi không cờ là required;
// route đọc không có IdempotencyMode.
func TestGeneratesIdempotencyModes(t *testing.T) {
	cases := []struct {
		file string
		want []string
	}{
		{"exempt-ok.yaml", []string{
			`{Method: "POST", Pattern: "POST /api/v1/quote", OperationID: "quoteCart", Permission: "things.read", Write: true, IdempotencyMode: "exempt", IdempotencyReason: "Chỉ tính giá từ thân yêu cầu, không ghi dữ liệu", Auth: "access"}`,
			`{Method: "POST", Pattern: "POST /api/v1/things", OperationID: "createThing", Permission: "things.write", Write: true, IdempotencyMode: "required", Auth: "access"}`,
			"IdempotencyMode   string",
			"IdempotencyReason string",
		}},
		{"noreplay-ok.yaml", []string{
			`{Method: "POST", Pattern: "POST /api/v1/service-keys", OperationID: "createServiceKey", Permission: "things.write", Write: true, IdempotencyMode: "no-replay", IdempotencyReason: "Trả khóa bí mật một lần; không được lưu thân trả lời", Auth: "access"}`,
		}},
	}
	for _, c := range cases {
		out := genOK(t, c.file)
		for _, w := range c.want {
			if !strings.Contains(out, w) {
				t.Errorf("%s: tệp sinh thiếu %q:\n%s", c.file, w, out)
			}
		}
	}
	_, _, out := runGen(t, filepath.Join("testdata", "ok.yaml"))
	if !strings.Contains(out, `{Method: "GET", Pattern: "GET /health/live", OperationID: "live", Public: true, Auth: "public"}`) {
		t.Errorf("route đọc không được mang IdempotencyMode:\n%s", out)
	}
}

